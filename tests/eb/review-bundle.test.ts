// The build read's review bundle (prereg 2026-11-11-geva-522 section 4): the fixed part order with each file's name as
// a heading, the word cap on both sides with the cut counted, a resume's rewrite, and the discarded repository edits.
// Keyless; every file is invented.
import { afterAll, describe, expect, test } from "bun:test";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { assembleBundle, BUNDLE_FILE, bundleParts, repoEdits, writeBundle } from "../../lanes/eng-build/bundle.ts";
import { EbError } from "../../lanes/eng-build/errors.ts";
import { FROZEN } from "../../lanes/eng-build/frozen.ts";
import { removeTree } from "../../src/trial/cleanup.ts";
import { ARTIFACT, nd, say, tree } from "../er/transcripts.ts";

const root = mkdtempSync(join(tmpdir(), "eb-bundle-test-"));
afterAll(() => removeTree(root));
const words = (n: number) => Array.from({ length: n }, (_, i) => "w" + i).join(" ");
const transcript = nd(say("First look."), say("Final reply: the plan now covers the empty ledger."));

describe("bundle parts", () => {
  test("pre-cut: plan.md, the final reply as review.md, then its test plan artifact", () => {
    const parts = bundleParts("precut", { plan: "# Plan\nImproved.\n", transcript, stateRoot: tree(ARTIFACT), coverage: null });
    expect(parts).toEqual([
      { name: "plan.md", text: "# Plan\nImproved.\n" },
      { name: "review.md", text: "Final reply: the plan now covers the empty ledger." },
      { name: "tester-main-eng-review-test-plan-20261108-101500.md", text: "# Test Plan\nGenerated by /plan-eng-review on 2026-11-08\n" },
    ]);
  });

  test("candidate: its plan-coverage files in their fixed order; a missing one is left out", () => {
    const coverage = tree({ "test-plan.md": "T1\n", "path-map.md": "P1 NEW\n", "notes.md": "not a skill file\n" });
    expect(bundleParts("candidate", { plan: "p\n", transcript, stateRoot: tree(ARTIFACT), coverage }).map((p) => p.name)).toEqual(["plan.md", "review.md", "path-map.md", "test-plan.md"]);
  });

  test("plain: plan.md and review.md only, and a session with no reply or plan gives neither", () => {
    expect(bundleParts("plain", { plan: "p\n", transcript, stateRoot: tree(ARTIFACT), coverage: null }).map((p) => p.name)).toEqual(["plan.md", "review.md"]);
    expect(bundleParts("plain", { plan: null, transcript: "", stateRoot: null, coverage: null })).toEqual([]);
  });
});

describe("bundle assembly and cap", () => {
  test("each part under its name as a heading, joined by a blank line", () => {
    const b = assembleBundle([{ name: "plan.md", text: "one two\n\n" }, { name: "review.md", text: "three" }]);
    expect(b.text).toBe("# plan.md\n\none two\n\n# review.md\n\nthree\n");
    expect(b).toMatchObject({ parts: ["plan.md", "review.md"], words: 7, fullWords: 7, truncated: false });
  });

  test("exactly the cap is kept whole; one word past it is cut and counted", () => {
    const cap = FROZEN.bundle.maxWords;
    const at = assembleBundle([{ name: "plan.md", text: words(cap - 2) }]);
    expect(at).toMatchObject({ words: cap, fullWords: cap, truncated: false });
    const over = assembleBundle([{ name: "plan.md", text: words(cap - 1) }]);
    expect(over).toMatchObject({ words: cap, fullWords: cap + 1, truncated: true });
    expect(over.text.endsWith("w" + (cap - 3) + " [cut]\n")).toBe(true);
  });

  test("written once as bundle.md; a resume reuses the same bytes and refuses other bytes", () => {
    const dir = join(root, "review");
    const b = assembleBundle([{ name: "plan.md", text: "same" }]);
    const path = writeBundle(dir, b);
    expect(path).toBe(join(dir, BUNDLE_FILE));
    expect(writeBundle(dir, b)).toBe(path);
    let code: string | null = null;
    try {
      writeBundle(dir, assembleBundle([{ name: "plan.md", text: "other" }]));
    } catch (e) {
      code = (e as EbError).code;
    }
    expect(code).toBe("E_EB_CACHE_STALE");
    expect(readFileSync(path, "utf8")).toBe(b.text);
  });
});

describe("discarded repository edits", () => {
  test("changed, added and removed files count; .git/ and the candidate's plan-coverage folder do not", () => {
    const base = join(root, "base");
    mkdirSync(join(base, "src"), { recursive: true });
    mkdirSync(join(base, ".git"), { recursive: true });
    writeFileSync(join(base, "src", "a.ts"), "export const a = 1;\n");
    writeFileSync(join(base, "src", "b.ts"), "export const b = 1;\n");
    writeFileSync(join(base, "README.md"), "readme\n");
    symlinkSync("README.md", join(base, "link"));
    const after = join(root, "after");
    cpSync(base, after, { recursive: true, verbatimSymlinks: true });
    expect(repoEdits(base, after)).toBe(0);
    writeFileSync(join(after, "src", "a.ts"), "export const a = 2;\n");
    writeFileSync(join(after, "src", "c.ts"), "export const c = 1;\n");
    rmSync(join(after, "README.md"));
    writeFileSync(join(after, ".git", "index"), "rewritten\n");
    mkdirSync(join(after, ".gstack", "plan-coverage"), { recursive: true });
    writeFileSync(join(after, ".gstack", "plan-coverage", "path-map.md"), "P1 NEW\n");
    expect(repoEdits(base, after)).toBe(3);
  });
});
