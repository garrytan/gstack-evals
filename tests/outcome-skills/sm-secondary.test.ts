import { afterAll, describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { FIX_TITLE, fixTitleDigest } from "../../lanes/outcome-skills/statemachines/langs.ts";
import { blocks, foundIt, laterFix, whatChanged } from "../../lanes/outcome-skills/statemachines/secondary.ts";

const head = (p: string) => "diff --git a/" + p + " b/" + p + "\n--- a/" + p + "\n+++ b/" + p + "\n";
/** Replaces n old lines at line with one new line, as git diff -U0 writes it. */
const rep = (p: string, line: number, n = 1, add = "new" + line) => head(p) + "@@ -" + line + "," + n + " +" + line + " @@\n" + Array.from({ length: n }, (_, i) => "-old" + (line + i) + "\n").join("") + "+" + add + "\n";
const created = (p: string, lines: string[]) => "diff --git a/" + p + " b/" + p + "\nnew file mode 100644\n--- /dev/null\n+++ b/" + p + "\n@@ -0,0 +1," + lines.length + " @@\n" + lines.map((l) => "+" + l + "\n").join("");

describe("blocks", () => {
  test("splits a context hunk into runs of changed lines in base coordinates", () => {
    const p = head("a.go") + "@@ -10,7 +10,8 @@\n c10\n c11\n c12\n-r13\n+a13\n c14\n+a15\n c15\n c16\n";
    expect(blocks(p).map((b) => [b.path, b.lo, b.hi, b.added, b.removed])).toEqual([["a.go", 13, 13, 1, 1], ["a.go", 14.5, 14.5, 1, 0]]);
  });
  test("an added file is one insertion at the top, a binary file has no block", () => {
    expect(blocks(created("n.go", ["a", "b"])).map((b) => [b.path, b.lo, b.hi, b.added])).toEqual([["n.go", 0.5, 0.5, 2]]);
    expect(blocks("diff --git a/x.png b/x.png\nBinary files a/x.png and b/x.png differ\n")).toEqual([]);
  });
});

describe("found it (20 lines, same file)", () => {
  const fix = rep("a.go", 100);
  test("20 lines away is found, 21 is not, another file never is", () => {
    expect(foundIt(rep("a.go", 120), fix, null)).toEqual({ found: true, nearest: 20, files: ["a.go"], found_not_fixed: null });
    expect(foundIt(rep("a.go", 121), fix, null).found).toBe(false);
    expect(foundIt(rep("a.go", 121), fix, null).nearest).toBe(21);
    expect(foundIt(rep("b.go", 100), fix, null)).toEqual({ found: false, nearest: null, files: [], found_not_fixed: null });
  });
  test("the distance runs from the edge of a multi-line fix hunk", () => {
    expect(foundIt(rep("a.go", 124), rep("a.go", 100, 5), null).found).toBe(true);
    expect(foundIt(rep("a.go", 125), rep("a.go", 100, 5), null).found).toBe(false);
  });
  test("found but not fixed needs the strict outcome", () => {
    expect(foundIt(rep("a.go", 101), fix, false).found_not_fixed).toBe(true);
    expect(foundIt(rep("a.go", 101), fix, true).found_not_fixed).toBe(false);
    expect(foundIt(rep("a.go", 300), fix, false).found_not_fixed).toBe(false);
  });
});

describe("what it changed", () => {
  const base: Record<string, string> = {
    ".gitattributes": "gen/*.go linguist-generated=true\n",
    "pkg/core/zz.go": "// Code generated by tool. DO NOT EDIT.\npackage core\n",
    "pkg/core/a.go": "package core\n",
  };
  const ctx = { lang: "go" as const, scopeDir: "pkg/core", testFiles: [], readBase: (p: string) => base[p] ?? null };
  test("counts files, lines, outside the folder, tests, build files, generated marks and state constructs", () => {
    const arm = [
      head("pkg/core/a.go") + "@@ -1,0 +2,3 @@\n+type Phase int\n+const (\n+\tIdle Phase = iota\n",
      rep("pkg/core/zz.go", 2),
      rep("gen/out.go", 4),
      rep("go.mod", 3),
      created("pkg/core/a_test.go", ["package core"]),
      rep("docs/readme.md", 1),
    ].join("");
    const w = whatChanged(arm, ctx);
    expect(w.files).toBe(6);
    expect(w.lines).toEqual({ added: 8, removed: 4 });
    expect(w.outside_folder).toEqual(["docs/readme.md", "gen/out.go", "go.mod"]);
    expect(w.test_files).toEqual(["pkg/core/a_test.go"]);
    expect(w.build_files).toEqual(["go.mod"]);
    expect(w.generated).toEqual([{ path: "gen/out.go", by: "gitattributes" }, { path: "pkg/core/zz.go", by: "header" }]);
    expect(w.state_constructs).toEqual({ enum: 1, sealed: 0, union: 0, table: 0 });
  });
  test("a construct moved within a file is not new, and test files never count", () => {
    const moved = head("pkg/core/a.go") + "@@ -5,1 +5,0 @@\n-\tIdle Phase = iota\n@@ -9,0 +9,1 @@\n+\tIdle Phase = iota\n";
    expect(whatChanged(moved, ctx).state_constructs.enum).toBe(0);
    expect(whatChanged(created("pkg/core/b_test.go", ["\tX = iota"]), ctx).state_constructs.enum).toBe(0);
  });
  test("an added file's own header marks it generated", () => {
    expect(whatChanged(created("pkg/core/g.go", ["// do not edit", "package core"]), ctx).generated).toEqual([{ path: "pkg/core/g.go", by: "header" }]);
  });
});

describe("fix-title word list", () => {
  test("matches fix titles and its digest is pinned", () => {
    for (const t of ["Fix overflow in reader", "fix: off by one", "bugfix for parser", "Fixes #12", "Resolve crash on empty input"]) expect(FIX_TITLE.test(t)).toBe(true);
    for (const t of ["Add docs", "Prefix the names", "Bump version"]) expect(FIX_TITLE.test(t)).toBe(false);
    expect(fixTitleDigest()).toMatch(/^[0-9a-f]{64}$/);
  });
});

describe("later-fix overlap on a fixture repository", () => {
  const dir = mkdtempSync(join(tmpdir(), "sm-later-"));
  afterAll(() => rmSync(dir, { recursive: true, force: true }));
  const git = (args: string[], date = "2026-01-01T00:00:00Z") => {
    const r = spawnSync("git", ["-c", "user.name=fixture", "-c", "user.email=fixture@localhost", "-c", "commit.gpgsign=false", ...args], { cwd: dir, encoding: "utf8", env: { ...process.env, GIT_COMMITTER_DATE: date } });
    if (r.status !== 0) throw new Error(r.stderr);
    return r.stdout.trim();
  };
  const lines = Array.from({ length: 200 }, (_, i) => "l" + (i + 1));
  const commit = (msg: string, date: string, files: Record<string, string[]>) => {
    for (const [p, ls] of Object.entries(files)) writeFileSync(join(dir, p), ls.join("\n") + "\n");
    git(["add", "-A"]);
    git(["commit", "-q", "--date", date, "-m", msg], date);
    return git(["rev-parse", "HEAD"]);
  };
  git(["init", "-q", "-b", "main"]);
  const base = commit("base", "2026-01-01T00:00:00Z", { "a.go": lines, "b.go": lines });
  const docs = [...Array.from({ length: 50 }, (_, i) => "doc" + i), ...lines];
  commit("Add docs", "2026-01-10T00:00:00Z", { "a.go": docs });
  const near = docs.slice(); near[151] = "changed";
  const fixNear = commit("Fix overflow in reader", "2026-01-20T00:00:00Z", { "a.go": near });
  const target = near.slice(); target[199] = "target";
  commit("fix: off by one (#727)", "2026-02-01T00:00:00Z", { "a.go": target });
  commit("Fix in the other file", "2026-01-25T00:00:00Z", { "b.go": ["x", ...lines] });
  const late = target.slice(); late[209] = "late";
  commit("Fix late", "2026-07-01T00:00:00Z", { "a.go": late });

  test("an in-window fix-titled commit near an outside hunk counts, mapped through earlier commits", () => {
    const arm = rep("a.go", 20) + rep("a.go", 40) + rep("a.go", 100) + rep("a.go", 150) + rep("a.go", 160);
    const r = laterFix(arm, rep("a.go", 20), dir, { base, pull: "727" });
    expect(r.outside).toBe(4);
    expect(r.overlapping).toBe(1);
    expect(r.hunks.find((h) => h.lo === 100)?.commits).toEqual([fixNear]);
    expect(r.hunks.find((h) => h.lo === 150)?.commits).toEqual([]);
    expect(r.hunks.find((h) => h.lo === 160)?.commits).toEqual([]);
    expect(r.excluded.length).toBe(1);
    expect(r.window).toEqual({ from: "2026-01-01T00:00:00Z", to: "2026-05-01T00:00:00Z" });
  });
  test("a commit named in exclude is left out", () => {
    expect(laterFix(rep("a.go", 100), rep("a.go", 20), dir, { base, pull: "1", exclude: [fixNear] }).overlapping).toBe(0);
  });
  test("4 lines away is not within 3", () => {
    expect(laterFix(rep("a.go", 98), rep("a.go", 20), dir, { base, pull: "727" }).overlapping).toBe(0);
    expect(laterFix(rep("a.go", 99), rep("a.go", 20), dir, { base, pull: "727" }).overlapping).toBe(1);
  });
});
