import { describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { contain } from "../../lanes/outcome-skills/statemachines/contain.ts";

// Value: protects=check (d)'s base filter on a tree that holds a binary blob with a marker in it; fails_when=a NUL line in
// the one-pass stream makes the exact-match grep read mark-lines as binary, so no marker counts as in the base and a common
// line the tree holds everywhere (SubtitleEdit-12151's "using System.Collections.Generic;") hits in build output, or when
// the fix lets a planted line through that is not a whole line of any base blob.
const MARK = "using System.Collections.Generic.Fixture.Probe;";
const HIDDEN = "    Assert.Equal(42, HiddenContainProbe.Run());  // hidden";
const OUT = "obj/Release/A.GlobalUsings.g.cs";
const git = (dir: string, ...args: string[]) => {
  const r = spawnSync("git", ["-C", dir, "-c", "user.name=t", "-c", "user.email=t@e", "-c", "init.defaultBranch=main", ...args], { encoding: "utf8" });
  if (r.status !== 0) throw new Error(r.stderr);
  return r.stdout.trim();
};
const blobId = (b: Buffer) => createHash("sha1").update(Buffer.concat([Buffer.from("blob " + b.length + "\0"), b])).digest("hex");
const sha = (s: string) => createHash("sha256").update(s).digest("hex");
const TEXT = Buffer.from("namespace Probe;\n" + MARK + "\npublic class A {}\n");
const binaryBefore = (body: string) => {
  let bin = Buffer.alloc(0);
  for (let i = 0; !bin.length || blobId(bin) >= blobId(TEXT); i++) bin = Buffer.concat([Buffer.from("tar" + i), Buffer.from([0]), Buffer.from(body)]);
  return bin;
};
const run = (base: Record<string, Buffer>, untracked: Record<string, Buffer>) => {
  const root = mkdtempSync(join(tmpdir(), "sm-contain-bin-"));
  const w = join(root, "w");
  mkdirSync(w, { recursive: true });
  git(w, "init", "-q");
  for (const [p, b] of Object.entries(base)) writeFileSync(join(w, p), b);
  git(w, "add", "-A");
  git(w, "commit", "-qm", "base");
  const want = git(w, "rev-parse", "HEAD");
  for (const [p, b] of Object.entries(untracked)) { mkdirSync(dirname(join(w, p)), { recursive: true }); writeFileSync(join(w, p), b); }
  const r = contain({ kind: "host", root, repo: w }, { want, names: [], markers: [MARK, HIDDEN] });
  expect([r.checks.refs.ok, r.checks.objects.ok, r.checks.stores.ok]).toEqual([true, true, true]);
  return r.checks.scan.findings;
};
const leak = (p: string, line: string) => "marker /w/" + p + " sha256=" + sha(line);

describe("check (d)'s base filter next to binary blobs (GST-1959)", () => {
  test("a binary blob holding a marker line does not hide the markers the base tree's text files hold", () => {
    const bin = binaryBefore(MARK + "\n");
    expect(blobId(bin) < blobId(TEXT)).toBe(true);
    expect(run({ "A.cs": TEXT, "sample.tar": bin }, { [OUT]: Buffer.from("// <auto-generated/>\n" + MARK + "\n" + HIDDEN + "\n") })).toEqual([leak(OUT, HIDDEN)]);
  });

  test("a planted line in no base blob still fails in a text file", () => {
    expect(run({ "A.cs": TEXT }, { [OUT]: Buffer.from("// <auto-generated/>\n" + HIDDEN + "\n") })).toEqual([leak(OUT, HIDDEN)]);
  });

  test("a planted line in no base blob still fails in a NUL-bearing file beside a binary base blob", () => {
    const bin = binaryBefore(MARK + "\n");
    const p = "bin/Release/Files/sample.dat";
    expect(run({ "A.cs": TEXT, "sample.tar": bin }, { [p]: Buffer.concat([Buffer.from("dat"), Buffer.from([0]), Buffer.from(HIDDEN + "\n")]) })).toEqual([leak(p, HIDDEN)]);
  });

  test("a planted line that a binary base blob holds only inside a longer line still fails", () => {
    const bin = binaryBefore("x" + HIDDEN + "y\n" + MARK + "\n");
    expect(run({ "A.cs": TEXT, "sample.tar": bin }, { [OUT]: Buffer.from(MARK + "\n" + HIDDEN + "\n") })).toEqual([leak(OUT, HIDDEN)]);
  });
});
